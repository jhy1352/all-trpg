/**
 * Helper to dynamically get specialized 20+ preset pool based on world settings
 */
export function getWorldTailoredMetaPool(world: WorldInfoState): MetaPools {
  const mode = world.worldMode;
  const name = (world.worldName || '').toLowerCase();
  const genre = (world.worldGenre || '').toLowerCase();
  const premise = (world.worldPremise || '').toLowerCase();

  const combined = `${name} ${genre} ${premise}`;

  if (combined.includes('주술') || combined.includes('애니') || combined.includes('jrpg') || combined.includes('학원') || combined.includes('페르소나') || combined.includes('이세계') || combined.includes('귀멸') || combined.includes('전생슬') || combined.includes('나혼렙') || combined.includes('블리치')) {
    return GENRE_META_POOLS.janime;
  }
  if (combined.includes('무협') || combined.includes('강호') || combined.includes('선협') || combined.includes('화산') || combined.includes('사조') || combined.includes('신조') || combined.includes('의천') || combined.includes('소림') || combined.includes('구파') || combined.includes('마교')) {
    return GENRE_META_POOLS.wuxia;
  }
  if (combined.includes('사이버') || combined.includes('sf') || combined.includes('우주') || combined.includes('넷러너') || combined.includes('메카') || combined.includes('아포칼립스') || combined.includes('황무지') || combined.includes('안드로이드')) {
    return GENRE_META_POOLS.scifi;
  }
  if (combined.includes('크툴루') || combined.includes('호러') || combined.includes('코스믹') || combined.includes('탐정') || combined.includes('오컬트') || combined.includes('흡혈귀') || combined.includes('괴담') || combined.includes('미스터리') || combined.includes('무당')) {
    return GENRE_META_POOLS.mystery;
  }

  // Default to rich high/dark fantasy pool
  return GENRE_META_POOLS.fantasy;
}
